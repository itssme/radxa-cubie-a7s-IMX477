#!/usr/bin/env python3
"""Evaluate a camera PNG against the ISP RGB calibration target."""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

import cv2
import numpy as np

from calibration_common import (
    compose_debug,
    detect_markers,
    draw_projected_grid,
    homography_from_centers,
    load_config,
    load_marker_override,
    make_rectified_debug,
    marker_json_payload,
    project_points_mm,
    rect_corners_mm,
    sample_polygon_rgb,
    save_json,
    similarity_from_rgb,
)


def evaluate(image_bgr: np.ndarray, cfg: dict, H: np.ndarray) -> list[dict]:
    results = []
    inset = float(cfg["sampling"]["inset_fraction"])
    for patch in cfg["patches"]:
        sample_mm = rect_corners_mm(patch["rect_mm"], inset)
        sample_px = project_points_mm(H, sample_mm)
        stats = sample_polygon_rgb(image_bgr, sample_px)
        expected = np.array(patch["rgb"], dtype=np.float64)
        measured = stats["median_rgb"]
        similarity, delta, mae, rmse = similarity_from_rgb(expected, measured)
        results.append({
            "id": patch["id"],
            "expected_rgb": [int(x) for x in expected],
            "median_rgb": [float(x) for x in measured],
            "mean_rgb": [float(x) for x in stats["mean_rgb"]],
            "std_rgb": [float(x) for x in stats["std_rgb"]],
            "delta_rgb": [float(x) for x in delta],
            "mae": mae,
            "rmse": rmse,
            "similarity_percent": similarity,
            "n_pixels": stats["n_pixels"],
        })
    return results


def print_report(results: list[dict], source: str, marker_source: str):
    print(f"Image: {source}")
    print(f"Marker positions: {marker_source}")
    print("Sampling: per-channel median over central 50% x 50% of each patch")
    print("Similarity: 100 * (1 - RGB channel MAE / 255)")
    print()
    print("Patch  Expected RGB    Median RGB      Delta RGB        MAE   RMSE   Similarity   Std RGB")
    print("-----  --------------  --------------  ---------------  ----  -----  ----------   ----------------")
    for r in results:
        e = tuple(r["expected_rgb"])
        m = tuple(int(round(x)) for x in r["median_rgb"])
        d = tuple(int(round(x)) for x in r["delta_rgb"])
        s = tuple(round(x, 1) for x in r["std_rgb"])
        print(f"{r['id']:5s}  {str(e):14s}  {str(m):14s}  {str(d):15s}  {r['mae']:4.1f}  {r['rmse']:5.1f}  {r['similarity_percent']:9.2f}%   {s}")

    sims = np.array([r["similarity_percent"] for r in results], dtype=np.float64)
    maes = np.array([r["mae"] for r in results], dtype=np.float64)
    rmses = np.array([r["rmse"] for r in results], dtype=np.float64)
    deltas = np.array([r["delta_rgb"] for r in results], dtype=np.float64)
    worst = min(results, key=lambda r: r["similarity_percent"])
    print()
    print("Summary")
    print(f"  Mean similarity   : {sims.mean():.2f}%")
    print(f"  Median similarity : {np.median(sims):.2f}%")
    print(f"  Worst patch       : {worst['id']} at {worst['similarity_percent']:.2f}%")
    print(f"  Mean patch MAE    : {maes.mean():.2f} RGB levels")
    print(f"  Mean patch RMSE   : {rmses.mean():.2f} RGB levels")
    print(f"  Mean signed bias  : R {deltas[:,0].mean():+.2f}, G {deltas[:,1].mean():+.2f}, B {deltas[:,2].mean():+.2f}")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("image", help="Camera image (.png recommended)")
    ap.add_argument("--config", required=True, help="Target config JSON generated by generate_target.py")
    ap.add_argument("--manual-json", help="Override ArUco detection using JSON from manual_click.py or --save-markers-json")
    ap.add_argument("--save-markers-json", help="Save current marker positions/rotations to a reusable override JSON")
    ap.add_argument("--debug", help="Optional debug PNG path. PNG is not written by default.")
    ap.add_argument("--debug-jpeg", help="Debug JPEG path; default: <image>_debug.jpg")
    ap.add_argument("--debug-jpeg-quality", type=int, default=90, help="JPEG quality for compressed debug image (default: 90)")
    ap.add_argument("--report-json", help="Optional machine-readable evaluation report")
    args = ap.parse_args()

    image_path = Path(args.image)
    image = cv2.imread(str(image_path), cv2.IMREAD_COLOR)
    if image is None:
        ap.error(f"Could not read image: {image_path}")
    cfg = load_config(args.config)

    marker_details = {}
    loaded_marker_data = None
    if args.manual_json:
        centers, loaded_marker_data = load_marker_override(args.manual_json, cfg)
        marker_source = f"marker override: {args.manual_json}"
        for mid_text, item in (loaded_marker_data.get("markers") or {}).items():
            if isinstance(item, dict):
                marker_details[int(mid_text)] = item
    else:
        detected, _ = detect_markers(image, cfg)
        centers = {mid: item["center_px"] for mid, item in detected.items()}
        marker_details = detected
        required = [int(x) for x in cfg["aruco"]["marker_order"]]
        missing = [mid for mid in required if mid not in centers]
        if missing:
            print(f"ERROR: ArUco detection did not find required marker IDs: {missing}", file=sys.stderr)
            print("Use manual_click.py to create a marker override JSON, then pass --manual-json <file>.", file=sys.stderr)
            return 2
        marker_source = "automatic ArUco detection"

    if args.save_markers_json:
        chart_rotation = None
        if loaded_marker_data is not None:
            chart_rotation = loaded_marker_data.get("chart_rotation_deg")
        payload = marker_json_payload(
            cfg,
            source_image=str(image_path),
            centers_px=centers,
            marker_details=marker_details,
            chart_rotation_deg=chart_rotation,
            source="eval_aruco_detection" if not args.manual_json else "eval_marker_override",
        )
        save_json(args.save_markers_json, payload)
        print(f"Saved marker JSON: {args.save_markers_json}")
        if "chart_rotation_deg" in payload:
            print(f"Detected chart rotation: {payload['chart_rotation_deg']:+.2f} deg")

    H = homography_from_centers(cfg, centers)
    results = evaluate(image, cfg, H)
    print_report(results, str(image_path), marker_source)

    overlay = draw_projected_grid(image, cfg, H, results)
    rectified = make_rectified_debug(image, cfg, H, results)
    composite = compose_debug(overlay, rectified)
    # JPEG is the default debug artifact to keep disk usage low.
    jpeg_quality = int(np.clip(args.debug_jpeg_quality, 1, 100))
    jpeg_path = Path(args.debug_jpeg) if args.debug_jpeg else image_path.with_name(image_path.stem + "_debug.jpg")
    jpeg_path.parent.mkdir(parents=True, exist_ok=True)
    if not cv2.imwrite(str(jpeg_path), composite, [int(cv2.IMWRITE_JPEG_QUALITY), jpeg_quality]):
        raise RuntimeError(f"Failed to write debug JPEG image: {jpeg_path}")
    print(f"  Debug image (JPG) : {jpeg_path} (quality={jpeg_quality})")

    # Only write a lossless PNG when explicitly requested.
    if args.debug:
        debug_path = Path(args.debug)
        debug_path.parent.mkdir(parents=True, exist_ok=True)
        if debug_path.suffix.lower() != ".png":
            raise ValueError("--debug should point to a .png file.")
        if not cv2.imwrite(str(debug_path), composite):
            raise RuntimeError(f"Failed to write debug PNG image: {debug_path}")
        print(f"  Debug image (PNG) : {debug_path}")

    if args.report_json:
        similarities = np.array([r["similarity_percent"] for r in results], dtype=np.float64)
        patch_maes = np.array([r["mae"] for r in results], dtype=np.float64)
        patch_rmses = np.array([r["rmse"] for r in results], dtype=np.float64)
        signed_bias = np.mean(np.array([r["delta_rgb"] for r in results]), axis=0)
        worst = min(results, key=lambda r: r["similarity_percent"])
        report = {
            "schema": "isp-color-chart-evaluation-v1",
            "image": str(image_path),
            "marker_source": marker_source,
            "results": results,
            "summary": {
                "mean_similarity_percent": float(np.mean(similarities)),
                "median_similarity_percent": float(np.median(similarities)),
                "mean_patch_mae": float(np.mean(patch_maes)),
                "mean_patch_rmse": float(np.mean(patch_rmses)),
                "mean_signed_bias_rgb": signed_bias.tolist(),
                "worst_patch": {
                    "id": worst["id"],
                    "similarity_percent": float(worst["similarity_percent"]),
                },
            },
        }
        save_json(args.report_json, report)
        print(f"  JSON report       : {args.report_json}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
