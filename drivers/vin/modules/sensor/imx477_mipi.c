static int sensor_g_exp(struct v4l2_subdev *sd, __s32 *value)
{
	struct sensor_info *info = to_state(sd);
	*value = info->exp;
	sensor_dbg("sensor_get_exposure = %d\n", info->exp);
	return 0;
}

static unsigned int sensor_effective_exp(unsigned int exp_val)
{
	if (force_exp_16line)
		exp_val = force_exp_16line;
	if (exp_val > IMX477_EXP_MAX)
		exp_val = IMX477_EXP_MAX;
	return exp_val;
}

static int sensor_effective_gain(int gain_val)
{
	if (force_gain_16)
		gain_val = force_gain_16;
	if (gain_val < IMX477_GAIN_MIN)
		gain_val = IMX477_GAIN_MIN;
	if (gain_val > IMX477_GAIN_MAX)
		gain_val = IMX477_GAIN_MAX;
	return gain_val;
}

/* These helpers program already validated values without reapplying overrides. */
static int sensor_program_exp(struct v4l2_subdev *sd, unsigned int exp_val)
{
	data_type explow, exphigh;
	struct sensor_info *info = to_state(sd);

	exp_val = (exp_val + 8) >> 4;
	exphigh = (unsigned char)((0xff00 & exp_val) >> 8);
	explow = (unsigned char)((0x00ff & exp_val));

	sensor_write(sd, 0x0203, explow);
	sensor_write(sd, 0x0202, exphigh);

	sensor_dbg("sensor_set_exp = %d line Done!\n", exp_val);

	info->exp = exp_val;
	return 0;
}

static int sensor_s_exp(struct v4l2_subdev *sd, unsigned int exp_val)
{
	return sensor_program_exp(sd, sensor_effective_exp(exp_val));
}

static int sensor_g_gain(struct v4l2_subdev *sd, __s32 *value)
{
	struct sensor_info *info = to_state(sd);
	*value = info->gain;
	sensor_dbg("sensor_get_gain = %d\n", info->gain);
	return 0;
}

static int sensor_program_gain(struct v4l2_subdev *sd, int gain_val)
{
	struct sensor_info *info = to_state(sd);
	data_type gainlow = 0;
	data_type gainhigh = 0;
	int gainana = 0;
	int upper = 0;
	int lower = 0;

	if (gain_val <= 22*16) {
		gainana = 1024 - 16384 / gain_val;
		upper = 0x01;
		lower = 0x00;
	} else {
		gainana = 978;
		upper = gain_val/(16*22);
		lower = 16*((gain_val%(16*22))/22);
	}

	gainlow = (unsigned char)(gainana & 0xff);
	gainhigh = (unsigned char)((gainana >> 8) & 0xff);

	sensor_write(sd, 0x0205, gainlow);
	sensor_write(sd, 0x0204, gainhigh);

	sensor_write(sd, 0x3ff9, 0x01);
	sensor_write(sd, 0x020e, upper);
	sensor_write(sd, 0x020f, lower);

	sensor_dbg("sensor_set_gain = %d, Done!\n", gain_val);
	info->gain = gain_val;

	return 0;
}

static int sensor_s_gain(struct v4l2_subdev *sd, int gain_val)
{
	return sensor_program_gain(sd, sensor_effective_gain(gain_val));
}

static int imx477_mipi_sensor_vts;
static int sensor_s_exp_gain(struct v4l2_subdev *sd,
			     struct sensor_exp_gain *exp_gain)
{
	int shutter, frame_length;
	struct sensor_info *info = to_state(sd);
	int exp_val, gain_val;

	/*
	 * The A733 large-image path runs two ISP instances.  Dynamic sensor
	 * control from that path currently collides with full-rate capture on
	 * the camera I2C bus, so retain the mode-table exposure and gain until
	 * large-image control is synchronized in the VIN/ISP stack.
	 */
	if (info->large_image == 3)
		return 0;

	exp_val = sensor_effective_exp(exp_gain->exp_val);
	gain_val = sensor_effective_gain(exp_gain->gain_val);

	shutter = exp_val / 16;
	if (shutter > imx477_mipi_sensor_vts - 4)
		frame_length = shutter + 4;
	else
		frame_length = imx477_mipi_sensor_vts;

	sensor_write(sd, 0x0341, (frame_length & 0xff));
	sensor_write(sd, 0x0340, (frame_length >> 8));

	sensor_program_exp(sd, exp_val);
	sensor_program_gain(sd, gain_val);

	sensor_dbg("sensor_set_gain exp = %d, %d Done!\n", gain_val, exp_val);

	info->exp = exp_val;
	info->gain = gain_val;
	return 0;
}

static int sensor_s_sw_stby(struct v4l2_subdev *sd, int on_off)
{
	int ret;
	data_type rdval;

	ret = sensor_read(sd, 0x3000, &rdval);
	if (ret != 0)
		return ret;

	if (on_off == STBY_ON)
		ret = sensor_write(sd, 0x0100, rdval & 0xfe);
	else
		ret = sensor_write(sd, 0x0100, rdval | 0x01);
	return ret;
}

